#!/usr/bin/env python3
"""Generate analog_tables.h from SynVOW's formant model.

VOWEL follows SynVOW's FormantEngine: the five reference vowels i, e, a, o, u
and their male formants F1-F3 plus a fixed F4, blended in the log domain along the vowel path
i-e-a-o-u. The 128 FREQ steps map to that path; the result is stored as a
fractional filter-table index (8.8) so the DSP can interpolate its coefficients.

BANK is four fixed resonators at 250/500/1000/2000 Hz, shifted as a group by
the FREQ knob.
"""
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# SynVOW FormantEngine.cpp: index order i, e, a, o, u, male averages, first three
# bands (F4/F5 are the fixed singer's formants, not vowel identity).
VOWEL_F = [
    [270.0, 530.0, 730.0, 570.0, 300.0],
    [2290.0, 1840.0, 1090.0, 840.0, 870.0],
    [3010.0, 2480.0, 2440.0, 2410.0, 2240.0],
]
VOWEL_X = [0.0, 0.0, 0.5, 1.0, 1.0]
VOWEL_Y = [0.0, 0.5, 1.0, 0.5, 0.0]
EPS = 1e-4
# SynVOW's fixed F4 singer's formant (male). It does not distinguish vowels;
# it fills the fourth biquad and keeps the synthetic voice from sounding hollow.
F4_HZ = 3300.0


def hz_table():
    text = open(os.path.join(ROOT, 'filter_tables.h')).read()
    body = text.split('HZ[128] = {')[1].split('};')[0]
    return [int(x) for x in re.findall(r'\d+', body)]


HZ = hz_table()


def fi8_for_hz(f):
    if f <= HZ[0]:
        return 0
    if f >= HZ[-1]:
        return (127 << 8) - 1
    for i in range(127):
        if HZ[i] <= f <= HZ[i + 1]:
            frac = (f - HZ[i]) * 256.0 / (HZ[i + 1] - HZ[i])
            return (i << 8) + int(round(frac))
    return (127 << 8) - 1


def vowel_freqs(t):
    seg = min(3, int(t * 4.0))
    local = t * 4.0 - seg
    x = VOWEL_X[seg] + (VOWEL_X[seg + 1] - VOWEL_X[seg]) * local
    y = VOWEL_Y[seg] + (VOWEL_Y[seg + 1] - VOWEL_Y[seg]) * local
    w = [1.0 / ((x - VOWEL_X[v]) ** 2 + (y - VOWEL_Y[v]) ** 2 + EPS)
         for v in range(5)]
    total = sum(w)
    out = []
    for band in range(3):
        acc = sum(w[v] * math.log(VOWEL_F[band][v]) for v in range(5))
        out.append(math.exp(acc / total))
    return out


def main():
    vowel = [[0] * 128 for _ in range(4)]
    for fi in range(128):
        freqs = vowel_freqs(fi / 127.0)
        for band in range(3):
            vowel[band][fi] = fi8_for_hz(freqs[band])
        vowel[3][fi] = fi8_for_hz(F4_HZ)
    bank = [fi8_for_hz(f) for f in (250.0, 500.0, 1000.0, 2000.0)]
    one27 = 1 << 27
    vgain = [int(round(g / 2.4 * one27)) for g in (1.0, 0.8, 0.6, 0.25)]
    bgain = [one27 // 4] * 4

    out = [
        '/* generated by tools/gen_analog_tables.py - do not edit',
        ' * VOWEL: fractional (8.8) filter-table index of F1-F4 along the SynVOW',
        ' * vowel path i-e-a-o-u, male formants. BANK: four fixed resonators.',
        ' * Gains are Q27 and normalised so the summed bank is unity at the peaks. */',
        '#ifndef ANALOG_TABLES_H',
        '#define ANALOG_TABLES_H',
        '',
        '#define VOWEL_N 4',
        '#define BANK_N 4',
        '',
        'static const unsigned short VOWEL_FI8[VOWEL_N][128] = {',
    ]
    for band in range(4):
        out.append('    {')
        for i in range(0, 128, 8):
            out.append('        ' + ', '.join('%5d' % v for v in vowel[band][i:i + 8]) + ',')
        out.append('    },')
    out += [
        '};',
        '',
        'static const int VOWEL_GAIN[VOWEL_N] = { %d, %d, %d, %d };' % tuple(vgain),
        '',
        'static const unsigned short BANK_BASE_FI8[BANK_N] = { %d, %d, %d, %d };'
        % tuple(bank),
        'static const int BANK_GAIN[BANK_N] = { %d, %d, %d, %d };' % tuple(bgain),
        '',
        '#endif',
        '',
    ]
    dest = os.path.join(ROOT, 'analog_tables.h')
    with open(dest, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote %s' % dest)
    print('vowel F1-F3 at 0, 32, 64, 96, 127:',
          [['%.0f' % v for v in vowel_freqs(i / 127.0)] for i in (0, 32, 64, 96, 127)])
    print('bank fi8:', bank)


if __name__ == '__main__':
    main()
