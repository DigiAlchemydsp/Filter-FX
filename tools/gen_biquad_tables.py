#!/usr/bin/env python3
"""Generate biquad_tables.h: RBJ band-pass biquads in Q30.

For every (K27 row ek = 8..15, FREQ step fi = 0..127):
    w0    = 2*pi*HZ[fi]/48000
    alpha = sin(w0) / (2Q),  Q = QX10[ek]/10
    b0 = alpha/(1+alpha), b2 = -b0
    a1 = -2*cos(w0)/(1+alpha), a2 = (1-alpha)/(1+alpha)

The kernel stores n1 = -a1 and n2 = -a2 so all three updates are MAC adds:
    y  = b0*x + z1
    z1 = n1*y + z2
    z2 = b2*x + n2*y
Coefficients are Q30 (range +-2), samples/state Q27, and `mac.l ...,<<` gives
Q27 products.
"""
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FS = 48000.0
QROWS = (8, 9, 10, 11, 12, 13, 14, 15)
NI = 128
SCALE = 1 << 30


def tables():
    text = open(os.path.join(ROOT, 'filter_tables.h')).read()
    hz = [int(x) for x in re.findall(r'\d+', text.split('HZ[128] = {')[1].split('};')[0])]
    qx = [int(x) for x in re.findall(r'\d+', text.split('QX10[16] = {')[1].split('};')[0])]
    return hz, qx


def q30(v):
    return int(round(v * SCALE))


def main():
    hz, qx = tables()
    rows = []
    lo = 1 << 31
    hi = -(1 << 31)
    for ek in QROWS:
        q = qx[ek] / 10.0
        row = []
        for fi in range(NI):
            w0 = 2.0 * math.pi * hz[fi] / FS
            alpha = math.sin(w0) / (2.0 * q)
            inv = 1.0 / (1.0 + alpha)
            b0 = alpha * inv
            b2 = -b0
            a1 = -2.0 * math.cos(w0) * inv
            a2 = (1.0 - alpha) * inv
            vals = (q30(b0), q30(b2), q30(-a1), q30(-a2))
            for v in vals:
                lo = min(lo, v)
                hi = max(hi, v)
            row.append(vals)
        rows.append(row)
    print('coefficient range', lo, hi, 'fits Q30:', -(1 << 31) <= lo and hi < (1 << 31))
    assert -(1 << 31) <= lo and hi < (1 << 31)

    out = [
        '/* generated by tools/gen_biquad_tables.py - do not edit',
        ' * RBJ band-pass biquads in Q30, rows ek = 8..15 (Q 1.7 .. 8).',
        ' * Per row/column: b0, b2, n1 = -a1, n2 = -a2. */',
        '#ifndef BIQUAD_TABLES_H',
        '#define BIQUAD_TABLES_H',
        '',
        'static const int BIQ_Q30[8][128][4] = {',
    ]
    for ek, row in zip(QROWS, rows):
        out.append('    {  /* ek %d */' % ek)
        for fi in range(NI):
            out.append('        { %10d, %10d, %10d, %10d },'
                       % row[fi])
        out.append('    },')
    out += ['};', '', '#endif', '']
    dest = os.path.join(ROOT, 'biquad_tables.h')
    with open(dest, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote %s (%d rows x %d x 4, %d bytes)' % (dest, len(QROWS), NI, len(QROWS) * NI * 16))


if __name__ == '__main__':
    main()
