#!/usr/bin/env python3
"""Generate mod_tables.h: sine/LFO/RING tables for the modulation FX."""
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FS = 48000.0


def hz_table():
    text = open(os.path.join(ROOT, 'filter_tables.h')).read()
    body = text.split('HZ[128] = {')[1].split('};')[0]
    return [int(x) for x in re.findall(r'\d+', body)]


def main():
    hz = hz_table()
    sine = [int(round(math.sin(2.0 * math.pi * i / 256.0) * 32767.0)) for i in range(256)]
    ring = [int(round(min(hz[i], 8000.0) * (1 << 32) / FS)) for i in range(128)]
    lfo = [int(round((0.05 * (160.0 ** (i / 127.0))) * (1 << 32) / FS)) for i in range(128)]

    out = ['/* generated by tools/gen_mod_tables.py - do not edit */',
           '#ifndef MOD_TABLES_H', '#define MOD_TABLES_H', '',
           'static const short SINE_Q15[256] = {']
    for i in range(0, 256, 12):
        out.append('    ' + ', '.join('%6d' % v for v in sine[i:i + 12]) + ',')
    out += ['};', '', 'static const unsigned int RING_INC[128] = {']
    for i in range(0, 128, 8):
        out.append('    ' + ', '.join('%10d' % v for v in ring[i:i + 8]) + ',')
    out += ['};', '', 'static const unsigned int LFO_INC[128] = {']
    for i in range(0, 128, 8):
        out.append('    ' + ', '.join('%10d' % v for v in lfo[i:i + 8]) + ',')
    out += ['};', '', '#endif', '']
    dest = os.path.join(ROOT, 'mod_tables.h')
    with open(dest, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote %s; ring inc %d..%d, LFO inc %d..%d'
          % (dest, ring[0], ring[-1], lfo[0], lfo[-1]))


if __name__ == '__main__':
    main()
